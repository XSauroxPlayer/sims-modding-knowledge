"""Regenerate INDEX.md from topics/ and sources/ front matter.

Usage: python tools/build_index.py
"""
from __future__ import annotations

import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def meta(p: Path) -> dict[str, str]:
    text = p.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    out = {}
    if m:
        for line in m.group(1).splitlines():
            if ":" in line:
                k, v = line.split(":", 1)
                out[k.strip()] = v.strip().strip('"')
    if "title" not in out:
        h = re.search(r"^# (.+)$", text, re.M)
        out["title"] = h.group(1) if h else p.stem
    return out


def main() -> None:
    lines = ["# Index", "", "Generated by `python tools/build_index.py`. Search: `python tools/search.py TERM ...`.", "",
             "## Topics (syntheses, start here)", ""]
    for p in sorted((ROOT / "topics").glob("*.md")):
        m = meta(p)
        lines.append(f"- [{m['title']}](topics/{p.name})" + (f" - {m['summary']}" if m.get("summary") else ""))
    lines += ["", "## Original research", ""]
    for p in sorted((ROOT / "research").glob("*.md")):
        m = meta(p)
        lines.append(f"- [{m['title']}](research/{p.name}) - {m.get('status', '')}")
    by_site: dict[str, list[Path]] = defaultdict(list)
    for p in sorted((ROOT / "sources").rglob("*.md")):
        by_site[p.parent.name].append(p)
    total = sum(len(v) for v in by_site.values())
    counts: Counter[str] = Counter()
    body = []
    for site, files in sorted(by_site.items()):
        body += ["", f"### {site} ({len(files)})", "", "| page | author | game | tags | status |", "|---|---|---|---|---|"]
        rows = []
        for p in files:
            m = meta(p)
            counts[m.get("status", "")] += 1
            rows.append((m["title"].lower(),
                         f"| [{m['title'].replace('|', '/')}](sources/{site}/{p.name}) | {m.get('author', '')} | {m.get('game', '')} | "
                         f"{m.get('tags', '')} | {m.get('status', '')} |"))
        body += [r[1] for r in sorted(rows)]
    summary = ", ".join(f"{n} {s}" for s, n in sorted(counts.items()))
    lines += ["", f"## Sources ({total} pages: {summary})", ""] + body
    (ROOT / "INDEX.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"INDEX.md: {total} sources ({summary})")


if __name__ == "__main__":
    main()
